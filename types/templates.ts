/**
 * Template and sharing types.
 * Prepares structure for template entities and subscription-based limits.
 */

/** Source of a garment template (local config, shared by user, or API). */
export type TemplateSource = 'local' | 'shared' | 'api';

/** Minimal metadata for a template when loaded from API or shared. */
export interface GarmentTemplateMetadata {
  /** Unique id (e.g. UUID from API, or local id). */
  id: string;
  /** Display name. */
  name: string;
  /** Where the template comes from. */
  source: TemplateSource;
  /** If source === 'shared', id of the user who shared it. */
  sharedFromUserId?: string;
  /** Optional timestamps for sync. */
  createdAt?: string;
  updatedAt?: string;
}

/**
 * Garment template as a loadable entity.
 * Extends the static GarmentType shape with metadata for sharing and limits.
 */
export interface GarmentTemplateMeta {
  templateId: string;
  source: TemplateSource;
  sharedFromUserId?: string;
}

/** Input type for measurement definitions (API-aligned). */
export type MeasurementInputTypeApi = 'number' | 'text' | 'select' | 'calculated';

/** Garment status from API (active = usable, disabled = visible but not for new orders). */
export type GarmentStatusApi = 'active' | 'disabled';

/**
 * Garment type record as returned by the API (configuration list/detail).
 * No hard-coded garment names; all from backend.
 */
export interface GarmentTypeRecord {
  id: string;
  name: string;
  /** Display label (prefer over name in UI when present). */
  label?: string | null;
  description?: string | null;
  status: GarmentStatusApi;
  source: TemplateSource;
  templateId?: string;
  sharedFromUserId?: string | null;
  /** Read-only: number of orders using this garment (when available). */
  orderCount?: number;
  createdAt?: string;
  updatedAt?: string;
}

/**
 * Measurement definition as returned by the API.
 * Key is generated by backend and immutable once created.
 */
export interface MeasurementDefinitionRecord {
  id: string;
  key: string;
  label: string;
  inputType: MeasurementInputTypeApi;
  displayOrder: number;
  unit?: string | null;
  unitKey?: string | null;
  required?: boolean;
  formula?: string | null;
  dependsOn?: string[] | null;
  options?: string[] | null;
  placeholder?: string | null;
  defaultValue?: string | null;
}

/** Payload to create a measurement definition. API requires key (stable id) and order. */
export interface CreateMeasurementDefinitionPayload {
  key: string;
  label: string;
  inputType: MeasurementInputTypeApi;
  order: number;
  unit?: string;
  unitKey?: string;
  required?: boolean;
  formula?: string;
  dependsOn?: string[];
  options?: string[];
  placeholder?: string;
  defaultValue?: string;
}

/** Payload to update a measurement definition. API uses order for sort order. */
export interface UpdateMeasurementDefinitionPayload {
  label?: string;
  inputType?: MeasurementInputTypeApi;
  order?: number;
  unit?: string | null;
  unitKey?: string | null;
  required?: boolean;
  formula?: string | null;
  dependsOn?: string[] | null;
  options?: string[] | null;
  placeholder?: string | null;
  defaultValue?: string | null;
}
